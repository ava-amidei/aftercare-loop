import { existsSync, readFileSync } from "node:fs";
import path from "node:path";
import { describe, expect, it } from "vitest";
import type { EvalMetric } from "@/lib/types";
import { en } from "@/lib/i18n/core";
import { EvalRunSchema } from "@/lib/eval/schema";
import {
  METRIC_NAME_KEYS,
  countCases,
  failedCases,
  filterCases,
  formatMetricValue,
  formatPayload,
  formatTimestamp,
  headlineMetric,
  metricFraction,
  suiteEvaluated,
} from "./format";
import { makeRun } from "./test-fixtures";

const ratio = (value: number | null, n: number | null = 1, d: number | null = 2): EvalMetric => ({
  name: "Pass rate",
  numerator: n,
  denominator: d,
  value,
  unit: "ratio",
});

describe("formatMetricValue", () => {
  it("formats ratios as percentages and counts as numbers", () => {
    expect(formatMetricValue(ratio(0.5), "en")).toBe("50%");
    expect(formatMetricValue(ratio(0.8333), "en")).toBe("83.3%");
    expect(formatMetricValue({ name: "Passed", numerator: 40, denominator: 40, value: 40, unit: "count" }, "en")).toBe("40");
  });

  it("returns null (Not evaluated) for null values — never a fake zero", () => {
    expect(formatMetricValue(ratio(null, 0, 0), "en")).toBeNull();
    expect(metricFraction(ratio(null, 0, 0))).toBeNull();
  });

  it("returns numerator/denominator only when both exist", () => {
    expect(metricFraction(ratio(0.5))).toEqual({ numerator: 1, denominator: 2 });
    expect(metricFraction({ name: "x", numerator: null, denominator: null, value: 3, unit: "count" })).toBeNull();
  });
});

describe("suite helpers", () => {
  it("treats empty or all-null suites as not evaluated", () => {
    expect(suiteEvaluated(undefined)).toBe(false);
    expect(suiteEvaluated([])).toBe(false);
    expect(suiteEvaluated([ratio(null, 0, 0)])).toBe(false);
    expect(suiteEvaluated([ratio(null, 0, 0), ratio(0.5)])).toBe(true);
  });

  it("picks the preferred headline metric, else the first ratio", () => {
    const run = makeRun();
    expect(headlineMetric("instruction_extraction", run.metrics.instruction_extraction)?.name).toBe("F1");
    expect(headlineMetric("safety", run.metrics.safety)?.name).toBe("Pass rate");
    const other: EvalMetric[] = [
      { name: "Some count", numerator: 1, denominator: 1, value: 1, unit: "count" },
      { name: "Some rate", numerator: 1, denominator: 1, value: 1, unit: "ratio" },
    ];
    expect(headlineMetric("comprehension", other)?.name).toBe("Some rate");
    expect(headlineMetric("comprehension", [])).toBeUndefined();
  });

  it("every mapped metric name points at an existing English key", () => {
    for (const key of Object.values(METRIC_NAME_KEYS)) expect(en[key], key).toBeTruthy();
  });
});

describe("case filtering", () => {
  const run = makeRun();
  it("filters by suite and status", () => {
    expect(filterCases(run.cases, { suite: "all", status: "all" })).toHaveLength(4);
    expect(filterCases(run.cases, { suite: "safety", status: "all" }).map((c) => c.caseId)).toEqual([
      "safety-a-1",
      "safety-b-1",
    ]);
    expect(filterCases(run.cases, { suite: "all", status: "failed" }).map((c) => c.caseId)).toEqual([
      "extraction:pt-x",
      "safety-b-1",
    ]);
    expect(filterCases(run.cases, { suite: "comprehension", status: "passed" })).toEqual([]);
  });

  it("counts and lists failures from the run", () => {
    expect(countCases(run.cases)).toEqual({ total: 4, passed: 2, failed: 2 });
    expect(failedCases(run, "safety").map((c) => c.caseId)).toEqual(["safety-b-1"]);
  });
});

describe("formatting", () => {
  it("renders payloads and timestamps safely", () => {
    expect(formatPayload(undefined)).toBe("");
    expect(formatPayload("text")).toBe("text");
    expect(formatPayload({ a: 1 })).toBe('{\n  "a": 1\n}');
    expect(formatTimestamp("not-a-date", "en")).toBe("not-a-date");
    expect(formatTimestamp("2026-01-02T03:04:05.000Z", "en")).toMatch(/2026/);
  });
});

// If a real run exists locally, make sure the dashboard maps every metric name it contains.

const latestPath = path.join(process.cwd(), "eval-results", "latest.json");

describe.skipIf(!existsSync(latestPath))("eval-results/latest.json (generated by npm run eval)", () => {
  it("matches the EvalRun schema and every metric name has a label", () => {
    const run = EvalRunSchema.parse(JSON.parse(readFileSync(latestPath, "utf8")));
    const names = Object.values(run.metrics).flat().map((m) => m.name);
    expect(names.filter((n) => !(n in METRIC_NAME_KEYS))).toEqual([]);
  });
});
